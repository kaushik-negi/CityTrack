class EvaluationTests(unittest.TestCase):
    def test_shortest(self):
        r=evaluate_case(CASES[0],1); self.assertTrue(r['exact']); self.assertEqual(r['error_pct'],0)
    def test_missing_shortest(self):
        self.assertTrue(evaluate_case(CASES[1],1)['exact'])
    def test_full_detour(self):
        self.assertTrue(evaluate_case(CASES[2],1)['exact'])
    def test_missing_detour(self):
        r=evaluate_case(CASES[3],1); self.assertFalse(r['exact']); self.assertAlmostEqual(r['error_pct'],100*.8/3.8); self.assertAlmostEqual(r['overlap'],.2)
    def test_loop(self):
        self.assertTrue(evaluate_case(CASES[4],1)['exact'])
    def test_disconnected(self):
        r=evaluate_case(CASES[5],1); self.assertFalse(r['success']); self.assertIsNone(r['error_pct'])
    def test_quality(self):
        q=quality_metrics(.90); self.assertEqual((q['tp'],q['fp'],q['fn'],q['tn']),(3,1,2,3)); self.assertAlmostEqual(q['precision'],.75); self.assertAlmostEqual(q['recall'],.6)
    def test_report(self):
        d=evaluate(); self.assertEqual((d['routed'],d['exact'],d['total']),(5,4,6)); h=html_report(d); self.assertIn('Trajectory evaluation lab',h); self.assertIn('No route',h)
    def test_empty(self):
        self.assertIsNone(reconstruct([])); self.assertIsNone(reconstruct(['UNKNOWN']))


def main():
    p=argparse.ArgumentParser(description=__doc__); p.add_argument('--test',action='store_true'); args=p.parse_args()
    if args.test:
        return 0 if unittest.TextTestRunner(verbosity=2).run(unittest.defaultTestLoader.loadTestsFromTestCase(EvaluationTests)).wasSuccessful() else 1
    data=evaluate(); out=Path(__file__).with_name('citytrack_evaluation.html'); out.write_text(html_report(data),encoding='utf-8')
    print(f"Routed: {data['routed']}/{data['total']} | Exact matches: {data['exact']}/{data['total']} | Mean distance error (routed): {data['mean_error']:.2f}% | Mean overlap (routed): {data['mean_overlap']:.1%}")
    print('Open the offline report:',out)
    return 0

if __name__=='__main__':
    raise SystemExit(main())
